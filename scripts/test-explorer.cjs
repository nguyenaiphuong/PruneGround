const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const crypto = require('node:crypto');
const path = require('node:path');
const os = require('node:os');
const root = path.resolve(__dirname, '..');
const shots = fs.mkdtempSync(path.join(os.tmpdir(), 'pruneground-browser-test-'));
const url = process.env.EXPLORER_URL || 'http://127.0.0.1:8765/#explorer';
const frame = (page) => page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
const hash = (bytes) => crypto.createHash('sha256').update(bytes).digest('hex');

(async () => {
  const browser = await chromium.launch({headless: true, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--no-sandbox']});
  const page = await browser.newPage({viewport: {width: 1440, height: 1100}, deviceScaleFactor: 1, reducedMotion: 'reduce'});
  const errors = [];
  const fullRequests = [];
  page.on('request', request => { if (request.url().includes('scene0011_00/full.ply')) fullRequests.push(request.url()); });
  page.on('pageerror', e => errors.push(e.message));
  const ready = async () => {
    await page.waitForFunction(() => document.querySelector('#pg-canvas-wrap').getAttribute('aria-busy') === 'false');
    assert.equal(await page.locator('#pg-webgl-error').isVisible(), false);
    await frame(page);
  };
  await page.goto(url);
  await ready();
  await page.locator('#pg-explorer').scrollIntoViewIfNeeded();
  assert.equal(await page.locator('canvas').count(), 1);
  assert.equal(await page.locator('img[src="assets/images/intuition.png"]').count(), 0);
  assert.equal(await page.locator('.mesh-details').getAttribute('open'), null);
  assert.equal(await page.locator('#pg-full-faces').textContent(), '451,905');
  assert.equal(await page.locator('#pg-pruned-faces').textContent(), '11,597');
  const canvas = page.locator('canvas');
  const initial = await canvas.screenshot();
  await page.locator('#pg-explorer').screenshot({path: shots + '/story-why.png'});
  await page.click('[data-pg-query="door"]');
  await ready();
  assert.match(await page.locator('#pg-choice-title').textContent(), /B.*doorway/);
  assert.match(await page.locator('#pg-continue-note').textContent(), /new inference run/);
  assert.equal(await page.locator('#pg-pruned-faces').textContent(), '160,164');
  assert.notEqual(hash(initial), hash(await canvas.screenshot()), 'Selecting a different chair must visibly change the canvas');
  assert.equal(await page.locator('.chair-door.selected').count(), 1);
  await page.click('#pg-top-view');
  await frame(page);
  assert.equal(await page.locator('#pg-top-view').getAttribute('aria-pressed'), 'true');
  await page.locator('#pg-explorer').screenshot({path: shots + '/story-top.png'});
  await page.click('#pg-reset-view');
  await frame(page);
  const rect = await canvas.boundingBox();
  const beforeOrbit = hash(await canvas.screenshot());
  await page.mouse.move(rect.x + rect.width / 2, rect.y + rect.height / 2);
  await page.mouse.down();
  await page.mouse.move(rect.x + rect.width / 2 + 100, rect.y + rect.height / 2 + 30, {steps: 8});
  await page.mouse.up();
  await frame(page);
  assert.notEqual(beforeOrbit, hash(await canvas.screenshot()), 'Orbit must change the rendered image');
  await page.mouse.wheel(0, -200);
  await frame(page);
  await page.click('#pg-reset-view');
  await page.click('#pg-continue');
  assert.match(await page.locator('#pg-transition-note').textContent(), /Same room, same description/);
  assert.match(await page.locator('#pg-query').textContent(), /nearest the doorway/);
  assert.equal(await page.locator('#pg-query-choices').isVisible(), false);
  assert.equal(await page.locator('#pg-scene-id').textContent(), 'scene0011_00');
  await page.click('[data-pg-stage="pruned"]');
  await frame(page);
  assert.match(await page.locator('#pg-view-label').textContent(), /Pruned region/);
  assert.match(await page.locator('#pg-stage-description').textContent(), /also keeps chair A/);
  await page.locator('#pg-explorer').screenshot({path: shots + '/story-pruned.png'});
  await page.click('[data-pg-stage="reformulated"]');
  const original = JSON.parse(fs.readFileSync(root + '/assets/3d/scene0011_00/door/reformulation.json'));
  assert.deepEqual(await page.locator('#pg-reformulation li').allTextContents(), [...original.target_properties, ...original.augmented_target_properties, ...original.utterances, ...original.augmented_utterances]);
  await page.locator('#pg-explorer').screenshot({path: shots + '/story-reformulated.png'});
  await page.click('[data-pg-stage="target"]');
  await frame(page);
  assert.equal(await page.locator('#pg-stage-badge').textContent(), 'Reference only');
  assert.match(await page.locator('#pg-grounding-note').textContent(), /not a PruneGround prediction/);
  assert.match(await page.locator('#pg-object-labels').textContent(), /Reference chair/);
  assert.match(await page.locator('#pg-object-labels').textContent(), /B · Reference/);
  assert.equal(await page.locator('.chair-door.selected').count(), 1);
  await page.locator('#pg-explorer').screenshot({path: shots + '/story-target.png'});
  for (const id of ['scene0025_00', 'scene0050_01']) {
    await page.selectOption('#pg-scene-select', id);
    await ready();
    assert.match(await page.locator('#pg-transition-note').textContent(), /Different room/);
    for (const stage of ['pruned', 'reformulated', 'target', 'full']) {
      await page.click('[data-pg-stage="' + stage + '"]');
      await frame(page);
      if (stage === 'target') {
        assert.equal(await page.locator('#pg-stage-badge').textContent(), 'Prediction not released');
        assert.equal(await page.locator('#pg-object-labels span').count(), 0);
      }
    }
  }
  // Rapid selections must end in the final room without stale meshes or query text.
  await page.selectOption('#pg-scene-select', 'scene0025_00');
  await page.selectOption('#pg-scene-select', 'scene0011_00');
  await ready();
  assert.match(await page.locator('#pg-query').textContent(), /nearest the doorway/);
  await page.click('#pg-tab-why');
  await ready();
  assert.equal(await page.locator('[data-pg-query="door"]').getAttribute('aria-pressed'), 'true');
  await page.click('[data-pg-query="tv"]');
  await ready();
  assert.equal(await page.locator('#pg-pruned-faces').textContent(), '11,597');
  await page.click('#pg-continue');
  assert.match(await page.locator('#pg-query').textContent(), /single chair nearest the TV/);
  await page.click('[data-pg-stage="target"]');
  assert.equal(await page.locator('.chair-tv.selected').count(), 1);
  assert.match(await page.locator('#pg-object-labels').textContent(), /A · Reference/);
  await page.click('#pg-tab-why');
  await page.click('[data-pg-query="door"]');
  await page.click('[data-pg-query="tv"]');
  await page.click('[data-pg-query="door"]');
  await ready();
  assert.equal(await page.locator('#pg-pruned-faces').textContent(), '160,164');
  assert.equal(await page.locator('.chair-door.selected').count(), 1);
  assert.equal(fullRequests.length, 1, 'Both query variants must share the full room download');
  await page.click('.mesh-details summary');
  assert.equal(await page.locator('.mesh-details').getAttribute('open'), '');
  await page.click('.mesh-details summary');
  await page.focus('#pg-tab-why');
  await page.keyboard.press('ArrowRight');
  assert.equal(await page.locator('#pg-tab-how').getAttribute('aria-selected'), 'true');
  await page.keyboard.press('Home');
  assert.equal(await page.locator('#pg-tab-why').getAttribute('aria-selected'), 'true');
  assert.equal(await page.locator('canvas').count(), 1);
  assert.deepEqual(errors, []);
  console.log('Desktop: two targets, top/reset/orbit/zoom, four stages, exact reformulation, three scenes, transitions, keyboard and one canvas passed.');

  await page.setViewportSize({width: 390, height: 844});
  await page.locator('#pg-explorer').scrollIntoViewIfNeeded();
  await page.click('#pg-reset-view');
  await frame(page);
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  assert.equal(overflow, false, 'Mobile layout must not overflow horizontally');
  await page.locator('#pg-explorer').screenshot({path: shots + '/story-mobile.png'});
  await page.click('#pg-tab-how');
  await page.click('[data-pg-stage="reformulated"]');
  await frame(page);
  await page.locator('#pg-explorer').screenshot({path: shots + '/story-mobile-how.png'});
  assert.equal(await page.locator('#pg-reformulation-panel').isVisible(), true);
  assert.deepEqual(errors, []);
  console.log('Mobile: responsive layout and pipeline controls passed.');
  console.log('Screenshots:', shots);
  await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
